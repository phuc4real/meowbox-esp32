#!/usr/bin/env python3
"""Generate theme tables from firmware/themes/*.json.

Outputs:
  components/ui/themes_gen.c   const theme_def_t g_themes[] for LVGL (see components/ui/include/theme.h)
  web/src/themes.css           [data-theme="<id>"] { --bg: ...; } blocks for the web UI
  ../pc-agent/src/ui/themes_gen.rs   the PC agent window's palettes (light/dark), shapes and display fonts

Fonts named in a theme that do not exist yet in components/fonts/*.c fall back to the base
Be Vietnam Pro fonts, so the firmware always builds.

Usage: python tools/gen_themes.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
AGENT_RS = ROOT.parent / "pc-agent" / "src" / "ui" / "themes_gen.rs"
# colours the agent window uses; "agent.light" overrides the day colours, "agent.dark" too (for Windows dark mode)
AGENT_KEYS = ["bg", "surface", "text", "dim", "line", "accent", "on_accent", "ok", "warn", "alert"]
AGENT_BTN = {"fill": "Fill", "cut": "Cut", "text": "Text", "raw": "Raw"}
THEMES = sorted((ROOT / "themes").glob("*.json"))
FONTS_DIR = ROOT / "components" / "fonts"
FALLBACK = {"small": "mb_font_14", "body": "mb_font_20", "title": "mb_font_20_bold", "clock": "mb_font_clock_64"}
COLOR_KEYS = ["bg", "surface", "text", "dim", "line", "accent", "accent2", "on_accent", "ok", "warn", "alert"]
BTN = {"fill": "THEME_BTN_FILL", "cut": "THEME_BTN_CUT", "text": "THEME_BTN_TEXT", "raw": "THEME_BTN_RAW"}
# Decorations the "Effects: saver" setting (display.fx = eco) turns off, on the speaker and on the web page alike.
# A theme lists the ones it has under "fx"; tilt is web-only (the speaker has nothing tilted).
FX_KEYS = ("aberration", "scanline", "grid", "hud", "tilt", "segments", "shadow")
CLOCK = {"left": "THEME_CLOCK_LEFT", "center": "THEME_CLOCK_CENTER", "enso": "THEME_CLOCK_ENSO", "block": "THEME_CLOCK_BLOCK"}


def hexc(s):
    return "0x" + s.lstrip("#").upper()


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def font(t, role):
    name = t["font"].get(role, FALLBACK[role])
    return name if (FONTS_DIR / f"{name}.c").exists() else FALLBACK[role]


def main():
    themes = [json.loads(p.read_text(encoding="utf-8")) for p in THEMES]
    themes.sort(key=lambda t: t.get("order", 99))
    defaults = [t["id"] for t in themes if t.get("default")]
    assert len(defaults) == 1, "exactly one theme must have \"default\": true"

    fonts_used = sorted({font(t, r) for t in themes for r in FALLBACK})
    out = ["/* Generated by tools/gen_themes.py from themes/<id>.json - do not edit. */",
           '#include "theme.h"', '#include "mb_fonts.h"', ""]
    for f in fonts_used:
        if not f.startswith("mb_font_"):
            out.append(f"LV_FONT_DECLARE({f})")
    out += ["", "const theme_def_t g_themes[] = {"]
    for t in themes:
        day = t["color"]
        night = {**{k: day[k] for k in COLOR_KEYS}, **{"ok": t["night"].get("accent"), "warn": t["night"].get("accent"),
                                                       "alert": t["night"].get("accent"), "accent2": t["night"].get("accent")},
                 **t["night"]}
        fx = t.get("fx", {})
        if set(fx) - set(FX_KEYS):
            raise SystemExit(f"{t['id']}: unknown fx {sorted(set(fx) - set(FX_KEYS))} (known: {', '.join(FX_KEYS)})")
        sh = t["shape"].get("shadow", [0, 0])

        def colors(c):
            return "{" + ", ".join(f".{k} = {hexc(c[k])}" for k in COLOR_KEYS) + "}"

        out.append("    {")
        out.append(f"        .id = {c_str(t['id'])}, .name_vi = {c_str(t['name']['vi'])}, .name_en = {c_str(t['name']['en'])},")
        out.append(f"        .desc_vi = {c_str(t['desc']['vi'])}, .desc_en = {c_str(t['desc']['en'])},")
        out.append(f"        .day = {colors(day)},")
        out.append(f"        .night = {colors(night)},")
        out.append(f"        .f_small = &{font(t, 'small')}, .f_body = &{font(t, 'body')}, "
                   f".f_title = &{font(t, 'title')}, .f_clock = &{font(t, 'clock')},")
        out.append(f"        .radius = {t['shape'].get('radius', 0)}, .border = {t['shape'].get('border', 0)}, "
                   f".shadow_x = {sh[0]}, .shadow_y = {sh[1]},")
        out.append(f"        .btn = {BTN[t['shape'].get('btn', 'fill')]}, .clock = {CLOCK[t['clock']['layout']]},")
        out.append("        " + " ".join(f".fx_{k} = {'true' if fx.get(k) else 'false'}," for k in FX_KEYS))
        out.append(f"        .cat_palette = {c_str(t['cat']['palette'])},")
        out.append(f"        .web_fonts = {c_str(','.join(t.get('web', {}).get('fonts', [])))},")
        out.append("    },")
    out += ["};", f"const int g_theme_count = {len(themes)};", f"const char *const g_theme_default = {c_str(defaults[0])};", ""]
    (ROOT / "components" / "ui" / "themes_gen.c").write_text("\n".join(out), encoding="utf-8")

    css = ["/* Generated by tools/gen_themes.py from themes/<id>.json - do not edit. */"]
    for t in themes:
        c = t["color"]
        w = t.get("web", {})
        sh = t["shape"].get("shadow", [0, 0])
        hs = t["shape"].get("hover_shadow", [0, 0])
        sel = f':root[data-theme="{t["id"]}"]' + (", :root:not([data-theme])" if t.get("default") else "")
        css.append(sel + " {")
        css.append(f"  color-scheme: {'light' if w.get('light', True) else 'dark'};")
        for k in COLOR_KEYS:
            css.append(f"  --{k.replace('_', '-')}: {c[k]};")
        css.append(f"  --radius: {t['shape'].get('radius', 0)}px;")
        css.append(f"  --border: {t['shape'].get('border', 0)}px;")
        css.append(f"  --shadow: {sh[0]}px {sh[1]}px 0 {c['line']};")
        css.append(f"  --hover-shadow: {hs[0]}px {hs[1]}px 0 {c['line']};")
        css.append(f"  --font-ui: {w.get('ui', 'system-ui, sans-serif')};")
        css.append(f"  --font-display: {w.get('display', 'system-ui, sans-serif')};")
        css.append(f"  --font-data: {w.get('data', 'ui-monospace, monospace')};")
        css.append(f"  --display-stretch: {w.get('display_stretch', '100%')};")
        css.append("}")
    (ROOT / "web" / "src" / "themes.css").write_text("\n".join(css) + "\n", encoding="utf-8")

    # theme list for the web (GET /api/themes is built from the same data in firmware; this is for the mock)
    # "fx": the Effects full/saver setting changes something for this theme (same rule as /api/themes in firmware)
    meta = [{"id": t["id"], "name": t["name"], "desc": t["desc"], "default": bool(t.get("default")),
             "fx": any(t.get("fx", {}).get(k) for k in FX_KEYS),
             "preview": f"/themes/{t['id']}.png", "fonts": t.get("web", {}).get("fonts", [])} for t in themes]
    (ROOT / "web" / "themes.json").write_text(json.dumps(meta, ensure_ascii=False, indent=2), encoding="utf-8")
    AGENT_RS.write_bytes(agent_rs(themes, defaults[0]).encode("utf-8"))

    print(f"{len(themes)} themes: {', '.join(t['id'] for t in themes)} (default {defaults[0]})")
    print("fonts:", ", ".join(fonts_used))


def agent_rs(themes, default):
    """The PC agent's copy (docs/enhance_agent.md, B1): day colours with the theme's agent overrides, a dark palette
    for Windows dark mode (not the speaker's night palette, made for a dim bedroom), shape and display font."""
    def rgb(h):
        h = h.lstrip("#")
        return "[" + ", ".join(f"0x{h[i:i + 2].upper()}" for i in (0, 2, 4)) + "]"

    def pal(c):
        return "Palette { " + ", ".join(f"{k}: {rgb(c[k])}" for k in AGENT_KEYS) + " }"

    out = ["// Generated by firmware/tools/gen_themes.py from firmware/themes/<id>.json - do not edit.",
           "use super::theme::{Btn, Palette, Shape, ThemeDef};", "",
           "pub const THEMES: &[ThemeDef] = &["]
    for t in themes:
        a = t.get("agent", {})
        if "display_font" not in a or "dark" not in a:
            raise SystemExit(f"{t['id']}: \"agent\" needs display_font and dark")
        light = {**t["color"], **a.get("light", {})}
        dark = {**t["color"], **a["dark"]}
        sh = t["shape"].get("shadow", [0, 0])
        out += ["    ThemeDef {",
                f"        id: {c_str(t['id'])},",
                f"        name: {c_str(t['name']['en'])},",
                f"        light: {pal(light)},",
                f"        dark: {pal(dark)},",
                f"        shape: Shape {{ radius: {t['shape'].get('radius', 0)}, border: {t['shape'].get('border', 0)}, "
                f"btn: Btn::{AGENT_BTN[t['shape'].get('btn', 'fill')]}, shadow: ({sh[0]}, {sh[1]}) }},",
                f"        display_font: {c_str(a['display_font'])},",
                "    },"]
    out += ["];", f"pub const DEFAULT: &str = {c_str(default)};", ""]
    return "\n".join(out)


if __name__ == "__main__":
    main()
