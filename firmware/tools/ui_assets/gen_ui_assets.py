#!/usr/bin/env python3
"""Convert UI art to LVGL A8 (alpha-only) images, recoloured at runtime with image_recolor.
   enso.png -> components/ui/ui_assets.c : ui_img_enso (150x150 A8)"""
import pathlib
from PIL import Image
HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent.parent / "components" / "ui" / "ui_assets.c"
items = [("ui_img_enso", HERE / "enso.png", 150)]
lines = ["/* Generated by tools/ui_assets/gen_ui_assets.py - do not edit. */", '#include "lvgl.h"', ""]
for name, path, size in items:
    a = Image.open(path).convert("RGBA").resize((size, size), Image.LANCZOS).split()[3]
    data = a.tobytes()
    lines.append(f"static const uint8_t {name}_data[] = {{")
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"const lv_image_dsc_t {name} = {{")
    lines.append(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = {size}, .h = {size}, .stride = {size}}},")
    lines.append(f"    .data_size = sizeof({name}_data),")
    lines.append(f"    .data = {name}_data,")
    lines.append("};")
    lines.append("")
OUT.write_text("\n".join(lines), encoding="utf-8")
print("wrote", OUT, sum(1 for _ in items), "images")
